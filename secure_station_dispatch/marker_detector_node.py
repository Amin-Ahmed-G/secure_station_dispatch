#!/usr/bin/env python3
"""
marker_detector_node.py
───────────────────────
Phase 1 (assignment): ArUco marker detection via OpenCV → StationMarker publisher.

Subscribes:
  /camera/image_raw   (sensor_msgs/Image)  – real or simulated camera feed
  /amcl_pose          (geometry_msgs/PoseWithCovarianceStamped) – robot pose
    OR /mock_pose     (geometry_msgs/PoseStamped) – used when running standalone

Publishes:
  /station_marker     (secure_station_dispatch/StationMarker)

Satisfies assignment requirement: "ArUco IDs" + "camera" integration.
When no real camera is available, a companion mock_image_publisher.py provides
a synthetic feed on /camera/image_raw. The detector does NOT care about the source.
"""

import os
import rclpy
from rclpy.node import Node
from rclpy.qos import QoSProfile, ReliabilityPolicy, HistoryPolicy

import cv2
import numpy as np
import yaml

import hmac
import hashlib

from sensor_msgs.msg import Image
from geometry_msgs.msg import PoseWithCovarianceStamped, PoseStamped
from cv_bridge import CvBridge
from builtin_interfaces.msg import Time as ROSTime

from secure_station_dispatch.msg import StationMarker   # generated by rosidl


# ─── ArUco API compatibility (OpenCV ≥ 4.7 changed the API) ──────────────────
def _make_aruco_detector(dict_name: str):
    """Return (detect_fn) that wraps both old and new OpenCV ArUco APIs."""
    dict_id = getattr(cv2.aruco, dict_name, cv2.aruco.DICT_4X4_50)
    try:
        # OpenCV ≥ 4.7
        aruco_dict = cv2.aruco.getPredefinedDictionary(dict_id)
        params = cv2.aruco.DetectorParameters()
        detector = cv2.aruco.ArucoDetector(aruco_dict, params)

        def detect(gray):
            return detector.detectMarkers(gray)

    except AttributeError:
        # OpenCV < 4.7 (legacy API)
        aruco_dict = cv2.aruco.Dictionary_get(dict_id)
        params = cv2.aruco.DetectorParameters_create()

        def detect(gray):
            return cv2.aruco.detectMarkers(gray, aruco_dict, parameters=params)

    return detect


# ─── Node ─────────────────────────────────────────────────────────────────────
class MarkerDetectorNode(Node):

    def __init__(self):
        super().__init__('marker_detector_node')

        # ── Parameters ────────────────────────────────────────────────────────
        self.declare_parameter('registry_path', '')
        self.declare_parameter('min_confidence', 0.75)
        self.declare_parameter('aruco_dictionary', 'DICT_4X4_50')
        self.declare_parameter('image_topic', '/camera/image_raw')
        self.declare_parameter('amcl_pose_topic', '/amcl_pose')
        self.declare_parameter('mock_pose_topic', '/mock_pose')

        registry_path = self.get_parameter('registry_path').value
        if not registry_path or not os.path.exists(registry_path):
            try:
                from ament_index_python.packages import get_package_share_directory
                pkg_share = get_package_share_directory('secure_station_dispatch')
                registry_path = os.path.join(pkg_share, 'config', 'station_registry.yaml')
            except Exception:
                dev_path = os.path.join(
                    os.path.dirname(__file__), '..', 'config', 'station_registry.yaml'
                )
                if os.path.exists(dev_path):
                    registry_path = dev_path

        self.registry = self._load_registry(registry_path)
        self.min_confidence: float = self.get_parameter('min_confidence').value
        dict_name: str = self.get_parameter('aruco_dictionary').value
        self.detect_markers = _make_aruco_detector(dict_name)
        self.bridge = CvBridge()

        # ── State ─────────────────────────────────────────────────────────────
        self._robot_pose: list[float] = [0.0] * 7  # x y z qx qy qz qw
        self._robot_pose[6] = 1.0                   # valid unit quaternion

        # ── QoS ───────────────────────────────────────────────────────────────
        sensor_qos = QoSProfile(
            reliability=ReliabilityPolicy.BEST_EFFORT,
            history=HistoryPolicy.KEEP_LAST,
            depth=1,
        )

        # ── Subscriptions ──────────────────────────────────────────────────────
        img_topic = self.get_parameter('image_topic').value
        self.image_sub = self.create_subscription(
            Image, img_topic, self._image_callback, sensor_qos
        )

        # Try AMCL first; fall back to mock_pose silently
        amcl_topic = self.get_parameter('amcl_pose_topic').value
        self.amcl_sub = self.create_subscription(
            PoseWithCovarianceStamped, amcl_topic, self._amcl_callback, 10
        )
        mock_topic = self.get_parameter('mock_pose_topic').value
        self.mock_pose_sub = self.create_subscription(
            PoseStamped, mock_topic, self._mock_pose_callback, 10
        )

        # ── Publisher ─────────────────────────────────────────────────────────
        self.marker_pub = self.create_publisher(StationMarker, '/station_marker', 10)

        self.get_logger().info(
            f'MarkerDetectorNode ready — watching {img_topic} '
            f'| registry: {len(self.registry)} stations'
        )

    # ── Registry ──────────────────────────────────────────────────────────────
    def _load_registry(self, path: str) -> dict:
        try:
            with open(path, 'r') as f:
                data = yaml.safe_load(f)
            stations = {int(k): v for k, v in data.get('stations', {}).items()}
            self.get_logger().info(
                f'Loaded station registry from {path}: '
                f'{list(stations.keys())} markers'
            )
            return stations
        except Exception as e:
            self.get_logger().error(f'Failed to load registry from {path}: {e}')
            # Minimal built-in fallback so node remains functional during testing
            return {
                0: {'station_name': 'Inspection Station', 'task_type': 'Inspection'},
                1: {'station_name': 'Assembly Station',   'task_type': 'Assembly'},
                2: {'station_name': 'Storage Station',    'task_type': 'Storage'},
                3: {'station_name': 'Charging Station',   'task_type': 'Charging'},
            }

    # ── Pose callbacks ────────────────────────────────────────────────────────
    def _amcl_callback(self, msg: PoseWithCovarianceStamped):
        p = msg.pose.pose
        o = p.orientation
        self._robot_pose = [
            p.position.x, p.position.y, p.position.z,
            o.x, o.y, o.z, o.w,
        ]

    def _mock_pose_callback(self, msg: PoseStamped):
        p = msg.pose
        o = p.orientation
        self._robot_pose = [
            p.position.x, p.position.y, p.position.z,
            o.x, o.y, o.z, o.w,
        ]

    # ── Image callback ────────────────────────────────────────────────────────
    def _image_callback(self, msg: Image):
        try:
            cv_image = self.bridge.imgmsg_to_cv2(msg, desired_encoding='bgr8')
        except Exception as e:
            self.get_logger().warn(f'cv_bridge conversion failed: {e}')
            return

        gray = cv2.cvtColor(cv_image, cv2.COLOR_BGR2GRAY)
        corners, ids, _ = self.detect_markers(gray)

        if ids is None or len(ids) == 0:
            return  # no markers in this frame

        now = self.get_clock().now().to_msg()

        for i, marker_id in enumerate(ids.flatten()):
            marker_id = int(marker_id)
            if marker_id not in self.registry:
                self.get_logger().debug(
                    f'Marker {marker_id} not in registry — ignoring'
                )
                continue

            confidence = self._estimate_confidence(corners[i])
            if confidence < self.min_confidence:
                self.get_logger().debug(
                    f'Marker {marker_id} confidence {confidence:.2f} below threshold'
                )
                continue

            station = self.registry[marker_id]
            hmac_sig = ''
            if 'hmac_key' in station:
                key = station['hmac_key'].encode('utf-8')
                payload = f"{marker_id}{station['station_name']}".encode('utf-8')
                hmac_sig = hmac.new(key, payload, hashlib.sha256).hexdigest()

            self._publish_marker(
                marker_id=marker_id,
                station_name=station['station_name'],
                confidence=confidence,
                stamp=now,
                hmac_signature=hmac_sig,
            )

    def _estimate_confidence(self, corner) -> float:
        """
        Heuristic confidence: ratio of marker perimeter² to image area.
        Returns a value in [0, 1]. Real deployments would use reprojection error.
        """
        pts = corner[0]  # shape (4, 2)
        perimeter = cv2.arcLength(pts, closed=True)
        # Normalise against a 'perfect' 300px marker on a 640×480 image
        normalised = min(perimeter / 1200.0, 1.0)
        return float(normalised)

    # ── Publish ───────────────────────────────────────────────────────────────
    def _publish_marker(
        self,
        marker_id: int,
        station_name: str,
        confidence: float,
        stamp: ROSTime,
        hmac_signature: str = '',   # Phase 2 placeholder (unused in Phase 1)
    ):
        msg = StationMarker()
        msg.marker_id = marker_id
        msg.station_name = station_name
        msg.robot_pose = list(self._robot_pose)  # float64[7]
        msg.confidence = confidence
        msg.stamp = stamp
        msg.hmac_signature = hmac_signature       # empty in Phase 1

        self.marker_pub.publish(msg)
        self.get_logger().info(
            f'[DETECT] Marker {marker_id} → {station_name} '
            f'(conf={confidence:.2f})'
        )


def main(args=None):
    rclpy.init(args=args)
    node = MarkerDetectorNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.try_shutdown()


if __name__ == '__main__':
    main()
